PRAGMA foreign_keys = ON;
CREATE TABLE users (id TEXT PRIMARY KEY, email TEXT NOT NULL UNIQUE, name TEXT NOT NULL, admin INTEGER NOT NULL DEFAULT 0, active INTEGER NOT NULL DEFAULT 1, units TEXT NOT NULL DEFAULT '[]', password TEXT);
CREATE TABLE sessions (token TEXT PRIMARY KEY, user TEXT NOT NULL REFERENCES users(id), expires INTEGER NOT NULL);
CREATE INDEX sessions_user ON sessions(user);
CREATE TABLE invites (token TEXT PRIMARY KEY, user TEXT NOT NULL UNIQUE REFERENCES users(id), expires INTEGER NOT NULL);
CREATE TABLE lots (id TEXT PRIMARY KEY, hash TEXT NOT NULL UNIQUE, data TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'ready');
CREATE TABLE records (id TEXT PRIMARY KEY, lot TEXT NOT NULL REFERENCES lots(id), unit TEXT NOT NULL, version INTEGER NOT NULL DEFAULT 0, data TEXT NOT NULL);
CREATE INDEX records_unit ON records(unit);
CREATE INDEX records_lot ON records(lot);
CREATE TABLE audit (id INTEGER PRIMARY KEY, at TEXT NOT NULL, user TEXT NOT NULL, action TEXT NOT NULL);
CREATE TABLE edits (id INTEGER PRIMARY KEY, at TEXT NOT NULL, user TEXT NOT NULL, record TEXT NOT NULL, before TEXT NOT NULL, after TEXT NOT NULL);
CREATE TABLE attempts (key TEXT PRIMARY KEY, n INTEGER NOT NULL, expires INTEGER NOT NULL);
